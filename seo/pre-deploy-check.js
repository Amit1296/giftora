/**
 * pre-deploy-check.js — Validation gate run automatically before every `git push`.
 *
 * Catches the bug classes that hit the live site in Sept 2026:
 *
 *  1. Dead sitemap URLs        («medicine-medical-equipments» 404s)  -> every <loc>
 *                              must resolve to a real file in an allowed directory
 *                              (repo root *.html OR products/*.html).
 *  2. Catalog drift            (repo 117/137 vs live Postgres 143)    -> the number of
 *                              product pages must match js/product-pages.js AND
 *                              data/products.json; every slug must have a page on disk.
 *  3. Derived/secret files     (js/products.js is regenerated by the server at boot)
 *                              must never be staged; data/backups/, previews/, artifacts/
 *                              and binaries are not repo content either.
 *  4. Invalid structured data  (truncated JSON-LD descriptions)       -> delegates to
 *                              seo/check-schema.js (exit != 0 fails the gate).
 *
 * Exit codes: 0 = OK, 1 = FAIL (block the push).
 *
 * Usage:
 *   node seo/pre-deploy-check.js [--no-schema] [--no-git]
 *
 *   --no-schema  skip the (slower) per-page structured-data scan
 *   --no-git     skip staged-file rules (e.g. on a machine without a git worktree)
 *   SITE_URL=... env override for the site base URL (default https://gift-ora.online)
 */

"use strict";

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const SITE_URL = (process.env.SITE_URL || "https://gift-ora.online").replace(/\/+$/, "");
const NO_SCHEMA = process.argv.includes("--no-schema");
const NO_GIT = process.argv.includes("--no-git");

const ALLOWED_DIRS = new Set(["", "products"]); // repo root only + products/
const FORBIDDEN_STAGED = [
  "js/products.js",               // boot-derived artifact (server regenerates from Postgres)
  "data/backups",                 // sync-script snapshots
  "previews",                     // dev scratch
  "artifacts",                    // dev scratch
];

const failures = [];
const warnings = [];

function fail(msg) { failures.push(msg); }
function warn(msg) { warnings.push(msg); }
function check(cond, msg) { cond ? undefined : fail(msg); }

function okHere(msg) { /* quiet on pass to keep output terse */ }

function readProductSlugs() {
  const file = path.join(ROOT, "js", "product-pages.js");
  if (!fs.existsSync(file)) { fail("js/product-pages.js missing; run node seo/sync-from-server.js"); return null; }
  const src = fs.readFileSync(file, "utf8");
  const m = src.match(/window\.GIFT_PRODUCT_PAGES\s*=\s*(\[[\s\S]*?\])\s*;/);
  if (!m) { fail("js/product-pages.js does not define window.GIFT_PRODUCT_PAGES"); return null; }
  return eval("(" + m[1] + ")");
}

function readSeedProducts() {
  const file = path.join(ROOT, "data", "products.json");
  if (!fs.existsSync(file)) { fail("data/products.json missing — seed must be committed"); return null; }
  try { return JSON.parse(fs.readFileSync(file, "utf8")); }
  catch { fail("data/products.json is not valid JSON"); return null; }
}

// ---- [1] Sitemap integrity ----
function parseSiteMap() {
  const file = path.join(ROOT, "sitemap.xml");
  if (!fs.existsSync(file)) { fail("sitemap.xml missing"); return null; }
  const txt = fs.readFileSync(file, "utf8");
  const locs = [...txt.matchAll(/<loc>\s*([^<\s]+?)\s*<\/loc>/g)].map((m) => m[1]);
  if (locs.length === 0) { fail("sitemap.xml contains 0 <loc> entries"); return null; }
  const seen = new Set();
  for (const u of locs) {
    if (seen.has(u)) { fail(`duplicate sitemap URL: ${u}`); }
    seen.add(u);
  }
  return locs;
}

function sitemapUrlToRel(url) {
  if (url.startsWith(SITE_URL)) return url.slice(SITE_URL.length);
  if (url.startsWith("/")) return url;
  fail(`sitemap URL is not under ${SITE_URL}: ${url}`);
  return null;
}

function checkSitemap(locs) {
  if (!locs) return;
  let productLocs = 0;
  for (const u of locs) {
    const rel = sitemapUrlToRel(u);
    if (rel === null) continue;
    const clean = rel === "/" ? "" : rel.replace(/^\/+/, "");
    // allowed directory?
    const seg = clean.includes("/") ? clean.split("/")[0] : "";
    if (!ALLOWED_DIRS.has(seg)) {
      fail(`sitemap URL outside allowed dirs (root, products/): ${u}`);
      continue;
    }
    if (seg === "products") productLocs++;
    if (clean === "") {
      check(fs.existsSync(path.join(ROOT, "index.html")), `sitemap / points to index.html but it is missing on disk`);
      continue;
    }
    let onDisk = clean;
    try { onDisk = decodeURIComponent(clean); } catch {}
    const file = path.join(ROOT, onDisk);
    check(fs.existsSync(file), `dead sitemap URL — no file on disk: ${u}`);
  }
  return productLocs;
}

// ---- [2] Catalog sync ----
function checkCatalog(sitemapProductLocs) {
  const slugs = readProductSlugs();
  const seed = readSeedProducts();
  if (slugs === null || seed === null) return;
  const seedCount = Array.isArray(seed) ? seed.length : 0;
  check(slugs.length === seedCount,
    `catalog mismatch: js/product-pages.js has ${slugs.length} slugs but data/products.json has ${seedCount} products — run node seo/sync-from-server.js`);
  if (sitemapProductLocs !== undefined && sitemapProductLocs !== null && sitemapProductLocs !== slugs.length) {
    fail(`catalog mismatch: sitemap advertises ${sitemapProductLocs} product URLs but product-pages.js has ${slugs.length} slugs`);
  }
  for (const slug of slugs) {
    if (typeof slug !== "string" || !/^[a-z0-9-]+$/.test(slug)) {
      fail(`suspicious slug in js/product-pages.js: ${JSON.stringify(slug)}`);
      continue;
    }
    check(fs.existsSync(path.join(ROOT, "products", decodeURIComponent(slug) + ".html")),
      `products/${slug}.html missing on disk but present in js/product-pages.js — regenerate products`);
  }
}

function sitemapHtmlPath(url) {
  if (url !== SITE_URL && !url.startsWith(SITE_URL + "/")) return null;
  const rel = url.slice(SITE_URL.length).replace(/^\/+/, "") || "index.html";
  try { return path.join(ROOT, decodeURIComponent(rel)); }
  catch { return null; }
}

function checkInternalLinks(locs) {
  if (!locs) return { pagesChecked: 0, linksChecked: 0, orphanCount: 0 };
  const reported = new Set();
  const sitemapPaths = new Set(locs.map(sitemapHtmlPath).filter(Boolean));
  const inbound = new Map([...sitemapPaths].map((file) => [file, 0]));
  let pagesChecked = 0;
  let linksChecked = 0;

  for (const url of locs) {
    const sourcePath = sitemapHtmlPath(url);
    if (!sourcePath || !fs.existsSync(sourcePath)) continue;
    pagesChecked++;
    const sourceRel = path.relative(ROOT, sourcePath).replace(/\\/g, "/");
    const html = fs.readFileSync(sourcePath, "utf8");
    const hrefs = new Set();
    for (const match of html.matchAll(/<a\b[^>]*?\bhref\s*=\s*(["'])(.*?)\1[^>]*>/gi)) {
      hrefs.add(match[2].trim());
    }

    for (const href of hrefs) {
      if (!href || href.startsWith("#") || /^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(href) || href.includes("%%")) continue;
      let targetPath;
      try {
        const clean = decodeURIComponent(href.split("#", 1)[0].split("?", 1)[0]);
        if (!clean) continue;
        targetPath = clean.startsWith("/")
          ? path.resolve(ROOT, "." + clean)
          : path.resolve(path.dirname(sourcePath), clean);
      } catch {
        const issue = `invalid local link in ${sourceRel}: ${href}`;
        if (!reported.has(issue)) { fail(issue); reported.add(issue); }
        continue;
      }

      linksChecked++;
      const targetRel = path.relative(ROOT, targetPath);
      if (targetRel.startsWith("..") || path.isAbsolute(targetRel)) {
        const issue = `local link escapes site root in ${sourceRel}: ${href}`;
        if (!reported.has(issue)) { fail(issue); reported.add(issue); }
        continue;
      }
      if (fs.existsSync(targetPath) && fs.statSync(targetPath).isDirectory()) {
        targetPath = path.join(targetPath, "index.html");
      }
      if (!fs.existsSync(targetPath)) {
        const issue = `dead internal link in ${sourceRel}: ${href} -> ${targetRel.replace(/\\/g, "/")}`;
        if (!reported.has(issue)) { fail(issue); reported.add(issue); }
        continue;
      }
      if (targetPath !== sourcePath && inbound.has(targetPath)) inbound.set(targetPath, inbound.get(targetPath) + 1);
    }
  }

  const orphans = [...inbound.entries()]
    .filter(([file, count]) => file !== path.join(ROOT, "index.html") && count === 0)
    .map(([file]) => path.relative(ROOT, file).replace(/\\/g, "/"));
  for (const orphan of orphans) fail(`sitemap page has no internal inbound links: ${orphan}`);

  return { pagesChecked, linksChecked, orphanCount: orphans.length };
}

// ---- [4] Staged-file rules ----
function gitFileList(args) {
  const r = spawnSync("git", args, { cwd: ROOT, encoding: "utf8" });
  if (r.status !== 0) return null;
  return (r.stdout || "").split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
}

function checkForbiddenFiles(files, label) {
  for (const name of files) {
    if (FORBIDDEN_STAGED.some((p) => name === p || name.startsWith(p + "/"))) {
      fail(`forbidden file ${label} (derived/scratch artifact): ${name}`);
    }
    if (/\.(exe|ps1)$/i.test(name)) {
      fail(`binary/credential file ${label}: ${name}`);
    }
    if (/(connect\.ps1|migrate|import_data|setup_db)/i.test(name)) {
      fail(`credential-carrying script ${label}: ${name}`);
    }
  }
}

function checkStagedFiles() {
  if (NO_GIT) return;
  // Staged (index vs HEAD) — relevant when running the gate BEFORE a commit.
  const staged = gitFileList(["diff", "--cached", "--name-only"]);
  if (staged === null) {
    warn("git diff --cached failed; staged-file rules skipped");
  } else {
    if (staged.length === 0) warn("nothing staged yet — `git add` first (pre-commit usage)");
    checkForbiddenFiles(staged, "staged");
  }
  // Pushed range (remote-tracking base..HEAD) — relevant when running the gate
  // FROM the pre-push hook, where nothing is staged anymore.
  const base = gitFileList(["rev-parse", "--verify", "--quiet", "origin/master"]);
  if (base !== null && base.length > 0) {
    const pushed = gitFileList(["diff", "--name-only", "origin/master..HEAD"]);
    if (pushed !== null) checkForbiddenFiles(pushed, "in pending push");
  }
}

// ---- [5] Structured data ----
function checkSchema() {
  if (NO_SCHEMA) return;
  if (!fs.existsSync(path.join(ROOT, "seo", "check-schema.js"))) {
    warn("seo/check-schema.js missing; schema check skipped");
    return;
  }
  const r = spawnSync(process.execPath, [path.join("seo", "check-schema.js")], { cwd: ROOT, encoding: "utf8" });
  process.stdout.write(r.stdout || "");
  process.stderr.write(r.stderr || "");
  if (r.status !== 0) fail(`seo/check-schema.js reported errors (exit ${r.status})`);
}

// ---- Run ----
console.log("Pre-deploy check — " + SITE_URL);
console.log("------------------------------------------------------------------");
function sectionStatus(beforeCount, note) {
  return failures.length > beforeCount ? "FAILED" + (note ? " " + note : "") : "ok";
}

console.log("  [1/5] sitemap integrity  ");
let before = failures.length;
const sitemapLocs = parseSiteMap();
const sitemapProductLocs = checkSitemap(sitemapLocs);
const s1 = failures.length > before;
console.log("        " + sectionStatus(before) + (sitemapLocs ? `  (${sitemapLocs.length} URLs, ${sitemapProductLocs} products)` : ""));

console.log("  [2/5] catalog sync       ");
before = failures.length;
checkCatalog(sitemapProductLocs);
console.log("        " + sectionStatus(before, s1 ? "(blocked — sitemap invalid)" : "(re-run node seo/sync-from-server.js)"));

console.log("  [3/5] internal links    ");
before = failures.length;
const linkStats = checkInternalLinks(sitemapLocs);
console.log("        " + sectionStatus(before) + `  (${linkStats.linksChecked} links across ${linkStats.pagesChecked} pages, ${linkStats.orphanCount} orphans)`);

console.log("  [4/5] staged/pushed files");
before = failures.length;
checkStagedFiles();
console.log("        " + sectionStatus(before));

console.log("  [5/5] structured data    ");
before = failures.length;
checkSchema();
console.log("        " + sectionStatus(before));

if (warnings.length) {
  console.log("\nWARNINGS:");
  warnings.forEach((w) => console.log("  [!] " + w));
}
if (failures.length) {
  console.log("\nERROR:");
  failures.forEach((f) => console.log("  [ ] " + f));
  console.log("\nRESULT: FAIL — fix before deploying (see seo/README.md for the workflow).");
  process.exit(1);
}
console.log("\nRESULT: OK — ready to push.");